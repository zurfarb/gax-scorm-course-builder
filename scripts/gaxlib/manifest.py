"""imsmanifest.xml generation for SCORM 1.2 and SCORM 2004 (3rd / 4th Edition).

All packages are single-SCO: one organization, one item, one resource that
lists every file in the package.
"""

import re
from xml.sax.saxutils import escape, quoteattr

SCORM_VERSIONS = ("1.2", "2004-4th", "2004-3rd")


def _identifier(*parts):
    """xs:ID-safe identifier: starts with a letter, only [A-Za-z0-9_.-]."""
    raw = "-".join(str(p) for p in parts if p)
    raw = re.sub(r"[^A-Za-z0-9_.-]+", "-", raw).strip("-")
    return "gax-" + raw


def _file_entries(files, indent):
    return "\n".join(f"{indent}<file href={quoteattr(f)}/>" for f in sorted(files))


def _generator_comment(generator):
    return f"<!-- Generated by {escape(generator)} -->\n" if generator else ""


def manifest_12(course, files, launch="index.html", generator=None):
    ident = _identifier(course["id"], course["language"], course["version"])
    title = escape(course["title"])
    # No adlcp:masteryscore on purpose: the LMS would then derive passed/failed
    # from the score and override the status the player reports.
    return f"""<?xml version="1.0" encoding="UTF-8"?>
{_generator_comment(generator)}<manifest identifier="{ident}" version="{escape(course['version'])}"
  xmlns="http://www.imsproject.org/xsd/imscp_rootv1p1p2"
  xmlns:adlcp="http://www.adlnet.org/xsd/adlcp_rootv1p2"
  xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
  xsi:schemaLocation="http://www.imsproject.org/xsd/imscp_rootv1p1p2 imscp_rootv1p1p2.xsd http://www.imsglobal.org/xsd/imsmd_rootv1p2p1 imsmd_rootv1p2p1.xsd http://www.adlnet.org/xsd/adlcp_rootv1p2 adlcp_rootv1p2.xsd">
  <metadata>
    <schema>ADL SCORM</schema>
    <schemaversion>1.2</schemaversion>
  </metadata>
  <organizations default="org">
    <organization identifier="org">
      <title>{title}</title>
      <item identifier="item-1" identifierref="res-1" isvisible="true">
        <title>{title}</title>
      </item>
    </organization>
  </organizations>
  <resources>
    <resource identifier="res-1" type="webcontent" adlcp:scormtype="sco" href="{escape(launch)}">
{_file_entries(files, "      ")}
    </resource>
  </resources>
</manifest>
"""


def manifest_2004(course, files, edition="4th", launch="index.html", generator=None):
    if edition not in ("3rd", "4th"):
        raise ValueError(f"unknown SCORM 2004 edition: {edition}")
    ident = _identifier(course["id"], course["language"], course["version"])
    title = escape(course["title"])
    adlnav_ns = '\n  xmlns:adlnav="http://www.adlnet.org/xsd/adlnav_v1p3"' if edition == "4th" else ""
    adlnav_loc = " http://www.adlnet.org/xsd/adlnav_v1p3 adlnav_v1p3.xsd" if edition == "4th" else ""
    # Explicit rollup rules and delivery controls: some LMSs otherwise show the
    # course as "unknown", or set completion themselves when the SCO exits.
    return f"""<?xml version="1.0" encoding="UTF-8"?>
{_generator_comment(generator)}<manifest identifier="{ident}" version="{escape(course['version'])}"
  xmlns="http://www.imsglobal.org/xsd/imscp_v1p1"
  xmlns:adlcp="http://www.adlnet.org/xsd/adlcp_v1p3"
  xmlns:adlseq="http://www.adlnet.org/xsd/adlseq_v1p3"{adlnav_ns}
  xmlns:imsss="http://www.imsglobal.org/xsd/imsss"
  xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
  xsi:schemaLocation="http://www.imsglobal.org/xsd/imscp_v1p1 imscp_v1p1.xsd http://www.adlnet.org/xsd/adlcp_v1p3 adlcp_v1p3.xsd http://www.adlnet.org/xsd/adlseq_v1p3 adlseq_v1p3.xsd{adlnav_loc} http://www.imsglobal.org/xsd/imsss imsss_v1p0.xsd">
  <metadata>
    <schema>ADL SCORM</schema>
    <schemaversion>2004 {edition} Edition</schemaversion>
  </metadata>
  <organizations default="org">
    <organization identifier="org" adlseq:objectivesGlobalToSystem="false">
      <title>{title}</title>
      <item identifier="item-1" identifierref="res-1" isvisible="true">
        <title>{title}</title>
        <imsss:sequencing>
          <imsss:deliveryControls tracked="true" completionSetByContent="true" objectiveSetByContent="true"/>
        </imsss:sequencing>
      </item>
      <imsss:sequencing>
        <imsss:controlMode choice="true" flow="true"/>
        <imsss:rollupRules rollupObjectiveSatisfied="true" rollupProgressCompletion="true" objectiveMeasureWeight="0">
          <imsss:rollupRule childActivitySet="all">
            <imsss:rollupConditions conditionCombination="all">
              <imsss:rollupCondition condition="completed"/>
            </imsss:rollupConditions>
            <imsss:rollupAction action="completed"/>
          </imsss:rollupRule>
          <imsss:rollupRule childActivitySet="any">
            <imsss:rollupConditions conditionCombination="all">
              <imsss:rollupCondition operator="not" condition="completed"/>
            </imsss:rollupConditions>
            <imsss:rollupAction action="incomplete"/>
          </imsss:rollupRule>
          <imsss:rollupRule childActivitySet="all">
            <imsss:rollupConditions conditionCombination="all">
              <imsss:rollupCondition condition="satisfied"/>
            </imsss:rollupConditions>
            <imsss:rollupAction action="satisfied"/>
          </imsss:rollupRule>
          <imsss:rollupRule childActivitySet="any">
            <imsss:rollupConditions conditionCombination="all">
              <imsss:rollupCondition operator="not" condition="satisfied"/>
            </imsss:rollupConditions>
            <imsss:rollupAction action="notSatisfied"/>
          </imsss:rollupRule>
        </imsss:rollupRules>
      </imsss:sequencing>
    </organization>
  </organizations>
  <resources>
    <resource identifier="res-1" type="webcontent" adlcp:scormType="sco" href="{escape(launch)}">
{_file_entries(files, "      ")}
    </resource>
  </resources>
</manifest>
"""


def build_manifest(course, files, scorm, generator=None):
    if scorm == "1.2":
        return manifest_12(course, files, generator=generator)
    if scorm == "2004-4th":
        return manifest_2004(course, files, "4th", generator=generator)
    if scorm == "2004-3rd":
        return manifest_2004(course, files, "3rd", generator=generator)
    raise ValueError(f"unknown SCORM version: {scorm}")
